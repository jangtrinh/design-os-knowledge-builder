"""Render the knowledge-builder CLI surface into skills/es-knowledge-forge/contract.txt.

The file's first line is `# sha256: <hex of everything after line 1>`. `--check` exits 1 when the
committed file differs from what the current source renders. Stdlib only, no network.
"""
import argparse
import hashlib
import sys
from pathlib import Path

sys.dont_write_bytecode = True
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
TARGET = ROOT / "skills" / "es-knowledge-forge" / "contract.txt"


class _Captured(Exception):
    def __init__(self, parser):
        self.parser = parser


def top_parser():
    """The fully registered argparse parser, captured from cli.main() without parsing anything."""
    import knowledge_builder.cli as cli

    def capture(self, *args, **kwargs):
        raise _Captured(self)

    original, argv = cli._Parser.parse_args, sys.argv
    cli._Parser.parse_args, sys.argv = capture, ["knowledge-builder"]
    try:
        cli.main()
    except _Captured as caught:
        return caught.parser
    finally:
        cli._Parser.parse_args, sys.argv = original, argv
    raise RuntimeError("cli.main() did not reach parse_args")


def option_line(action):
    if action.option_strings:
        name = ", ".join(action.option_strings)
    else:
        name = f"<{action.dest}>"
    facts = []
    if action.option_strings and action.required:
        facts.append("required")
    if action.nargs not in (None, 0):
        facts.append(f"nargs={action.nargs}")
    if action.type is not None:
        facts.append(f"type={getattr(action.type, '__name__', str(action.type))}")
    if action.choices:
        facts.append("choices=" + "|".join(map(str, action.choices)))
    if action.option_strings and action.default not in (None, False, argparse.SUPPRESS):
        facts.append(f"default={action.default!r}")
    if action.__class__.__name__ in ("_StoreTrueAction", "_AppendAction"):
        facts.append("flag" if action.__class__.__name__ == "_StoreTrueAction" else "repeatable")
    note = f"  [{'; '.join(facts)}]" if facts else ""
    return f"  {name}{note}  {(action.help or '').strip()}".rstrip()


def walk(parser, path, help_text, lines):
    subs = [a for a in parser._actions if isinstance(a, argparse._SubParsersAction)]
    if len(path) > 1:
        lines.append(f"## {' '.join(path)}" + (f" — {help_text}" if help_text else ""))
    for action in parser._actions:
        if isinstance(action, (argparse._HelpAction, argparse._SubParsersAction)):
            continue
        lines.append(option_line(action))
    if len(path) > 1:
        lines.append("")
    for sub in subs:
        helps = {a.dest: a.help for a in sub._choices_actions}
        for name, child in sub.choices.items():
            walk(child, [*path, name], helps.get(name, ""), lines)


def constants(lines):
    from knowledge_builder.ontology import claim_promote, create_object_params
    from knowledge_builder.ontology.action_defaults import DEFAULT_ACTIONS
    from knowledge_builder.ontology.hosting_hosts import HOSTING_HOSTS
    from knowledge_builder.research.ledger import CLAIM_TYPES
    from knowledge_builder.research.run_state import SETTERS

    lines += ["## action parameters (--param key=value)",
              f"  create-object  always: {', '.join(create_object_params.ALWAYS)}; document types add: "
              f"{', '.join(create_object_params.DOCUMENT)} (repeatable: {', '.join(sorted(create_object_params.REPEATABLE))}); "
              "plus the object type's declared properties",
              f"  promote-claim  {', '.join(sorted(claim_promote.PARAMS))}  (batch: JSONL, one object per line)"]
    for name, spec in DEFAULT_ACTIONS.items():
        if name != "create-object":
            lines.append(f"  {name}  {', '.join(spec['parameters'])}")
    lines += ["", "## run state set --key", "  " + ", ".join(sorted(SETTERS)), "",
              "## atom claim_type", "  " + ", ".join(sorted(CLAIM_TYPES)), "",
              "## hosting hosts (never a publisher)", "  " + ", ".join(HOSTING_HOSTS), ""]


def render():
    lines = ["# knowledge-builder CLI contract (generated by scripts/generate-skill-contract.py; do not edit)", ""]
    walk(top_parser(), ["knowledge-builder"], "", lines)
    constants(lines)
    body = "\n".join(lines).rstrip() + "\n"
    return f"# sha256: {hashlib.sha256(body.encode('utf-8')).hexdigest()}\n{body}".encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when contract.txt is stale")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if TARGET.is_symlink() or not TARGET.is_file() or TARGET.read_bytes() != expected:
            print("contract: regenerate contract.txt with scripts/generate-skill-contract.py", file=sys.stderr)
            return 1
        print("ok: contract")
        return 0
    TARGET.write_bytes(expected)
    print(TARGET.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
